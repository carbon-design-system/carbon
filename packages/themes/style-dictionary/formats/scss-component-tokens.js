'use strict';

/**
 * Emits the Sass module for one component: a map variable per token, keyed by
 * theme.
 *
 *   $button-danger-active: (
 *     white-theme: #a2191f,
 *     g-10: #a2191f,
 *     g-90: #a2191f,
 *     g-100: #a2191f,
 *   ) !default;
 */

const FILE_BANNER = `// Code generated by @carbon/themes. DO NOT EDIT.
//
// Copyright IBM Corp. 2018, 2023
//
// This source code is licensed under the Apache-2.0 license found in the
// LICENSE file in the root directory of this source tree.
//
`;

/**
 * Normalize a theme name to the Carbon SCSS convention.
 * @param {string} theme
 * @returns {string}
 */
function normalizeThemeName(theme) {
  if (theme === 'white') return 'white-theme';
  if (/^g\d+$/.test(theme)) return theme.replace(/^g(\d+)$/, 'g-$1');
  return theme;
}

/**
 * Serialize a CSS value to a Sass literal.
 * @param {string|number} value
 * @returns {string}
 */
function toSassLiteral(value) {
  if (typeof value === 'number') return String(value);
  if (typeof value !== 'string') return JSON.stringify(value);
  if (value.startsWith('#') || value.startsWith('rgb')) return value;
  if (
    value.endsWith('px') ||
    value.endsWith('em') ||
    value.endsWith('%') ||
    value === '0'
  )
    return value;
  return `string.unquote("${value}")`;
}

/**
 * @param {Array<{ name: string, values: Record<string, string> }>} tokens
 * @returns {string}
 */
function scssComponentTokens(tokens) {
  const variableBlocks = tokens.map(({ name, values }) => {
    const entries = Object.entries(values)
      .map(([theme, value]) => {
        return `  ${normalizeThemeName(theme)}: ${toSassLiteral(value)},`;
      })
      .join('\n');

    return `\n$${name}: (\n${entries}\n) !default;`;
  });

  return (
    FILE_BANNER +
    `\n@use 'sass:map';\n` +
    `@use 'sass:string';\n` +
    variableBlocks.join('\n') +
    '\n'
  );
}

module.exports = scssComponentTokens;
