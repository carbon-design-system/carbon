'use strict';

/**
 * Emits `_themes.scss`: one Sass map variable per theme, each followed by the
 * `utilities.merge` call that folds in the layout spacing and type tokens.
 */

const FILE_BANNER = `// Code generated by @carbon/themes. DO NOT EDIT.
//
// Copyright IBM Corp. 2018, 2023
//
// This source code is licensed under the Apache-2.0 license found in the
// LICENSE file in the root directory of this source tree.
//
`;

const SCSS_IMPORTS = `@use 'sass:map';
@use 'sass:string';
@use '@carbon/layout';
@use '@carbon/type';
@use '../utilities';
`;

/**
 * Serialize a CSS color value to a Sass literal.
 *
 * - Hex colors   → bare hex       (e.g.  #ffffff)
 * - rgba()       → bare function  (e.g.  rgba(141, 141, 141, 0.5))
 * - Strings      → string.unquote("…")
 * - Numbers      → bare number
 *
 * @param {string|number} value
 * @returns {string}  Sass source fragment
 */
function toSassLiteral(value) {
  if (typeof value === 'number') {
    return String(value);
  }
  if (typeof value !== 'string') {
    return JSON.stringify(value);
  }
  if (value.startsWith('#')) {
    return value;
  }
  if (
    value.startsWith('rgb') ||
    value.endsWith('px') ||
    value.endsWith('em') ||
    value.endsWith('%') ||
    value.endsWith('vw') ||
    value.endsWith('vh') ||
    value === '0'
  ) {
    return value;
  }
  // Plain string (e.g. 'light', 'dark')
  return `string.unquote('${value}')`;
}

/**
 * @param {Array<{ name: string, tokens: Array<{ name: string, value: string }> }>} themes
 * @returns {string}
 */
function scssThemes(themes) {
  const maps = themes.map(({ name, tokens }) => {
    const entries = [...tokens]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((token) => `  ${token.name}: ${toSassLiteral(token.value)},`)
      .join('\n');

    return (
      `$${name}: (\n${entries}\n) !default;\n` +
      `$${name}: utilities.merge(\n` +
      `  $${name},\n` +
      `  layout.$spacing,\n` +
      `  layout.$fluid-spacing,\n` +
      `  type.$tokens\n` +
      `);\n`
    );
  });

  return FILE_BANNER + '\n' + SCSS_IMPORTS + '\n' + maps.join('\n');
}

module.exports = scssThemes;
