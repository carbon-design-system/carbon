'use strict';

/**
 * Generates scss/generated/_hex-fallbacks.scss from color-palette.json.
 *
 * The output is a single Sass map: $oklch-to-hex that maps every
 * CSS oklch() string used in the Carbon palette to its sRGB hex equivalent.
 *
 * This map is consumed by the -custom-property mixin in _theme.scss when
 * $enable-oklch-fallback is true.  The mixin emits each custom property
 * declaration twice — hex/rgba first, oklch second — so browsers that predate
 * CSS Color Level 4 (Chrome < 111, Firefox < 113, Safari < 15.4) receive a
 * usable sRGB colour instead of an invisible/transparent value.
 *
 * Run order: must execute AFTER generateDTCGColorAliases() because it reads
 * the colour-palette.json that step writes.
 *
 * @returns {string} Absolute path of the written file.
 */

const fs = require('fs-extra');
const path = require('path');

/**
 * Round n to 4 decimal places — mirrors formatOklch() in dtcg-converter.js so
 * the generated keys match the CSS strings that dtcg-converter emits.
 * @param {number} n
 * @returns {number}
 */
function r4(n) {
  return Math.round(n * 1e4) / 1e4;
}

/**
 * Format an oklch { l, c, h } object as the 4dp CSS string used throughout
 * the Carbon DTCG pipeline.  Must match formatOklch() in dtcg-converter.js.
 * @param {{ l: number, c: number, h: number }} oklch
 * @returns {string}  e.g. "oklch(0.5565 0.243 261.95)"
 */
function formatOklch({ l, c, h }) {
  return `oklch(${r4(l)} ${r4(c)} ${r4(h)})`;
}

/**
 * Generate scss/generated/_hex-fallbacks.scss.
 * @returns {string} Absolute path of the written file.
 */
function generateHexFallbacks() {
  const palettePath = path.resolve(
    __dirname,
    '../../src/dtcg/color-palette.json'
  );
  const palette = JSON.parse(fs.readFileSync(palettePath, 'utf8'));

  const seen = new Set();
  const entries = [];

  for (const [family, scales] of Object.entries(palette)) {
    if (family.startsWith('$')) continue;
    for (const [, token] of Object.entries(scales)) {
      const oklch =
        token.$extensions &&
        token.$extensions['org.carbon'] &&
        token.$extensions['org.carbon'].oklch;
      const hex = token.$value && token.$value.hex;
      if (!oklch || !hex) continue;

      const key = formatOklch(oklch);
      if (seen.has(key)) continue; // identical oklch → same hex; skip duplicate
      seen.add(key);
      entries.push({ key, hex });
    }
  }

  const header = [
    '// Code generated by @carbon/themes. DO NOT EDIT.',
    '//',
    '// Copyright IBM Corp. 2018, 2026',
    '//',
    '// This source code is licensed under the Apache-2.0 license found in the',
    '// LICENSE file in the root directory of this source tree.',
    '//',
    '',
    '/// Map of oklch() CSS strings to their sRGB hex fallback values.',
    '/// Used by the -custom-property mixin when $enable-oklch-fallback is true.',
    '/// Generated from color-palette.json — do not edit by hand.',
  ].join('\n');

  const mapLines = entries.map(({ key, hex }) => `  '${key}': '${hex}',`);
  const content = `${header}\n$oklch-to-hex: (\n${mapLines.join('\n')}\n) !default;\n`;

  const outputPath = path.resolve(
    __dirname,
    '../../scss/generated/_hex-fallbacks.scss'
  );

  fs.ensureDirSync(path.dirname(outputPath));
  fs.writeFileSync(outputPath, content, 'utf8');

  return outputPath;
}

module.exports = generateHexFallbacks;
