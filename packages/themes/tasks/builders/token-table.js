'use strict';

/**
 * Generates `docs/generated/theme-tokens.md`: every theme and component token
 * with its value in each theme side by side. The token files hold one theme
 * each, so this is the place to compare a token across themes.
 */

const fs = require('fs-extra');
const path = require('path');
const { resolveThemes } = require('../../style-dictionary/sd.config');
const { readResolver } = require('../../style-dictionary/resolver');

const ROOT = path.resolve(__dirname, '../..');
const RESOLVER = path.join(ROOT, 'tokens', 'themes.resolver.json');
const OUTPUT = path.resolve(ROOT, '../../docs/generated/theme-tokens.md');
const THEME_TOKEN_FILE = 'theme';

/**
 * How a token value is written in its token file, e.g. `{gray.50} @ 0.12`.
 *
 * @param {string | object} value
 * @returns {string | undefined} `undefined` for values that are not references
 */
function formatSource(value) {
  if (typeof value === 'string') {
    return value;
  }
  if (value.components.$ref) {
    // "#/gray/50/$value/components" → "{gray.50}"
    const tokenPath = value.components.$ref.split('/').slice(1, -2);
    return `{${tokenPath.join('.')}} @ ${value.alpha}`;
  }
  return undefined;
}

/**
 * Reads the token values as written in the token files.
 *
 * @returns {Record<string, Record<string, Record<string, string | object>>>}
 *   file name → token name → theme name → `$value`
 */
function readSources() {
  const resolver = readResolver(RESOLVER);
  const sources = {};
  for (const theme of resolver.contexts('theme')) {
    for (const filepath of resolver.resolve({ theme }).source) {
      const name = path.basename(filepath, '.tokens.json');
      sources[name] ??= {};
      for (const [tokenName, token] of Object.entries(
        fs.readJsonSync(filepath)
      )) {
        if (tokenName.startsWith('$')) {
          continue;
        }
        sources[name][tokenName] ??= {};
        sources[name][tokenName][theme] = token.$value;
      }
    }
  }
  return sources;
}

function table(themeNames, tokenSources, resolved) {
  const rows = Object.entries(tokenSources).map(([tokenName, values]) => {
    const cells = themeNames.map((theme) => {
      if (!(theme in values)) {
        return '—';
      }
      const source = formatSource(values[theme]);
      const value = `\`${resolved[theme][tokenName]}\``;
      return source ? `\`${source}\` → ${value}` : value;
    });
    return `| \`${tokenName}\` | ${cells.join(' | ')} |`;
  });

  return [
    `| Token | ${themeNames.join(' | ')} |`,
    `| --- | ${themeNames.map(() => '---').join(' | ')} |`,
    ...rows,
  ].join('\n');
}

/**
 * @returns {Promise<string>} the path of the written file
 */
async function generateTokenTable() {
  const themes = await resolveThemes();
  const themeNames = themes.map((theme) => theme.name);
  const sources = readSources();

  const sections = Object.entries(sources).map(([name, tokenSources]) => {
    const resolved = {};
    for (const theme of themes) {
      const tokens =
        name === THEME_TOKEN_FILE ? theme.tokens : theme.components[name];
      resolved[theme.name] = Object.fromEntries(
        tokens.map((token) => [token.name, token.value])
      );
    }

    const heading =
      name === THEME_TOKEN_FILE ? 'Theme tokens' : `\`${name}\` tokens`;
    return [
      `## ${heading}`,
      `Source: \`packages/themes/tokens/themes/<theme>/${name}.tokens.json\``,
      table(themeNames, tokenSources, resolved),
    ].join('\n\n');
  });

  const content = [
    '# Theme tokens',
    '<!-- Code generated by @carbon/themes. DO NOT EDIT. -->',
    'Every `@carbon/themes` token with its value in each theme. A cell shows the value as written in the token file, then the color it resolves to. `{gray.50}` is a color from `packages/colors/tokens/colors.tokens.json` and `@ 0.12` is the alpha applied to it.',
    ...sections,
  ].join('\n\n');

  fs.outputFileSync(OUTPUT, content + '\n', 'utf8');
  return OUTPUT;
}

module.exports = generateTokenTable;
