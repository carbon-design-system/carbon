'use strict';

const fs = require('fs-extra');
const path = require('path');
const { convertDTCGToTheme } = require('./dtcg-converter');
const {
  generateV12OklchTheme,
  generateHexFallbackTheme,
} = require('./generate-v12-oklch');

const FILE_BANNER = `// Code generated by @carbon/themes. DO NOT EDIT.
//
// Copyright IBM Corp. 2018, 2026
//
// This source code is licensed under the Apache-2.0 license found in the
// LICENSE file in the root directory of this source tree.
`;

/**
 * Build _hex-fallbacks.scss for browsers that do not support OKLCH
 * Emits CSS variables under @supports not (color: oklch(0 0 0))
 */
function buildHexFallbacksFile() {
  const dtcgDir = path.resolve(__dirname, '../../src/dtcg');
  const themeNames = ['white', 'g10', 'g90', 'g100'];

  const lines = [FILE_BANNER, '@supports not (color: oklch(0 0 0)) {'];

  themeNames.forEach((themeName) => {
    const jsonPath = path.join(dtcgDir, `${themeName}.json`);
    if (!fs.existsSync(jsonPath)) return;

    const dtcgTokens = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    const theme = convertDTCGToTheme(dtcgTokens);

    const isDark = themeName === 'g90' || themeName === 'g100';
    const oklchTheme = generateV12OklchTheme(isDark ? 'dark' : 'light');
    Object.assign(theme, oklchTheme);

    const hexTheme = generateHexFallbackTheme(theme);

    const selector =
      themeName === 'white'
        ? ':root, [data-carbon-theme="white"]'
        : `[data-carbon-theme="${themeName}"]`;

    lines.push(`  ${selector} {`);
    for (const [key, value] of Object.entries(hexTheme).sort(([a], [b]) =>
      a.localeCompare(b)
    )) {
      if (typeof value === 'string' && value.startsWith('#')) {
        lines.push(`    --cds-${key}: ${value};`);
      }
    }
    lines.push('  }');
  });

  lines.push('}');
  return lines.join('\n') + '\n';
}

module.exports = buildHexFallbacksFile;
