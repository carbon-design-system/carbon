// Colors are now expressed in OKLCH format: oklch(L C H)
// where L = lightness (0–1), C = chroma, H = hue angle (0–360).
// The original hex value is preserved as an inline comment on each line.
// This is a breaking change — consumers that parsed values as hex strings
// must update to use the oklch() string or derive hex via a color library.
export type OklchColor = string; // 'oklch(L C H)' format
export type ColorScale = Record<number, OklchColor>;
export type ColorGroup = Record<string, ColorScale>;
export type HoverColorGroup = Record<string, OklchColor | ColorScale>;

